// The bundle is committed so the skill and the MCP app serve one file and never build anything.

import { readFileSync, writeFileSync } from "node:fs";
import { build } from "rolldown";

const TEMPLATE = new URL("../page/index.html", import.meta.url);
const OUT = new URL("../skills/chartroom/index.html", import.meta.url);
const ENTRY = '<script src="main.ts"></script>';

const { output } = await build({
  input: new URL("../page/main.ts", import.meta.url).pathname,
  write: false,
  output: { format: "iife" },
});
const [chunk] = output;
const template = readFileSync(TEMPLATE, "utf8");
if (!template.includes(ENTRY)) {
  throw new Error(`page/index.html should load the page with ${ENTRY}`);
}
const page = template
  .replace("<html", "<!-- Generated by `pnpm build` from page/: edit those files, not this one. -->\n<html")
  .replace(ENTRY, () => `<script>\n${chunk.code.trimEnd()}\n</script>`);

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== page) {
    console.error("skills/chartroom/index.html is out of date: run pnpm build and commit it");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, page);
}
